// Builds js/data/words.js from the curated lists in scripts/lists and the system dictionary.
// Usage: node scripts/build-words.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const list = (name) =>
  [...new Set(readFileSync(join(root, 'scripts/lists', name), 'utf8').split(/\s+/).filter(Boolean))];

const answers5 = list('answers5.txt');
const common4 = list('common4.txt');
for (const w of answers5) if (!/^[a-z]{5}$/.test(w)) throw new Error(`bad 5-letter answer: ${w}`);
for (const w of common4) if (!/^[a-z]{4}$/.test(w)) throw new Error(`bad 4-letter word: ${w}`);

const dictPath = '/usr/share/dict/words';
const dict = existsSync(dictPath)
  ? readFileSync(dictPath, 'utf8').split('\n').filter((w) => /^[a-z]+$/.test(w))
  : [];
const byLen = (n) => dict.filter((w) => w.length === n);
const d3 = new Set(byLen(3)), d4 = new Set(byLen(4));

// Valid guesses: dictionary words plus simple inflections, so reasonable guesses aren't rejected.
const valid5 = new Set([...byLen(5), ...answers5]);
for (const w of [...d4, ...common4]) {
  valid5.add(w + 's');
  if (w.endsWith('e')) valid5.add(w + 'd');
}
for (const w of d3) { valid5.add(w + 'ed'); valid5.add(w + 'es'); valid5.add(w + 'er'); }
const supplement5 = ['emoji', 'pixel', 'vlogs', 'texts', 'memes', 'selfie', 'robot', 'app'];
supplement5.filter((w) => w.length === 5).forEach((w) => valid5.add(w));

const valid4 = new Set([...d4, ...common4]);
for (const w of d3) valid4.add(w + 's');

const sorted = (s) => [...s].sort();
const out = `// Generated by scripts/build-words.mjs — do not edit by hand.
window.WH_WORDS = {
  answers5: ${JSON.stringify(answers5.join(' '))}.split(' '),
  common4: ${JSON.stringify(common4.join(' '))}.split(' '),
  valid5: ${JSON.stringify(sorted(valid5).join(''))},
  valid4: ${JSON.stringify(sorted(valid4).join(''))},
};
`;
writeFileSync(join(root, 'js/data/words.js'), out);
console.log(`answers5=${answers5.length} common4=${common4.length} valid5=${valid5.size} valid4=${valid4.size}`);
const missing = answers5.filter((w) => dict.length && !dict.includes(w));
if (missing.length) console.log('answers not in system dict (kept):', missing.join(' '));
