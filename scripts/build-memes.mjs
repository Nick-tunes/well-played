// Checks the meme content and bundles it into js/data/memes.js for Deep Cuts and Timeline.
//   content/memes/memes.json     the meme database (from the Memeory project)
//   content/memes/prompts.json   fallback Deep Cuts prompts (dates without a curated day, and practice)
//   content/memes/days/*.json    curated meme days: { date, deep: [{ where }], timeline: { memes } }
// Usage: node scripts/build-memes.mjs [--check]   (--check validates without writing)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'content/memes');
const read = (f) => JSON.parse(readFileSync(f, 'utf8'));
const memes = read(join(dir, 'memes.json'));
const prompts = read(join(dir, 'prompts.json'));
delete prompts._about;
const days = {};
for (const f of existsSync(join(dir, 'days')) ? readdirSync(join(dir, 'days')).filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort() : []) {
  const d = read(join(dir, 'days', f));
  days[f.slice(0, 10)] = { deep: d.deep, timeline: d.timeline };
}

// Load the real game rules so the check matches what players get.
const packed = memes.map((m) => [m.id, m.name, m.aliases || [], m.year, m.platform, m.source, m.star, m.type, m.tags || [], m.niche, m.fact || null]);
const sandbox = { console, Math, Date, JSON, WH_MEMES: packed, WH_MEME_PROMPTS: prompts, WH_MEME_DAYS: days };
sandbox.window = sandbox;
sandbox.addEventListener = sandbox.removeEventListener = () => {};
sandbox.document = { addEventListener() {}, removeEventListener() {}, hidden: true };
vm.createContext(sandbox);
for (const f of ['js/core.js', 'js/games/memes.js']) vm.runInContext(readFileSync(join(root, f), 'utf8'), sandbox, { filename: f });
const { fits, promptText, byId } = sandbox.WH.memes;

const errors = [], warns = [];
const ids = new Set();
for (const m of memes) {
  if (ids.has(m.id)) errors.push(`meme ${m.id}: duplicate id`);
  ids.add(m.id);
  if (![1, 2, 3, 4, 5].includes(m.niche)) errors.push(`meme ${m.id}: niche must be 1-5`);
  if (!Number.isInteger(m.year) || m.year < 2000) errors.push(`meme ${m.id}: bad year ${m.year}`);
}
const pool = (w) => memes.filter((m) => fits(m, w));
const checkPrompt = (w, at, min = 8) => {
  const p = pool(w), deep = p.filter((m) => m.niche >= 4).length;
  if (p.length < min) errors.push(`${at}: only ${p.length} memes fit "${promptText({ where: w })}" (need ${min}+)`);
  if (deep < 3) warns.push(`${at}: only ${deep} niche 4-5 answers for "${promptText({ where: w })}"`);
};
for (const [kind, list] of Object.entries(prompts)) list.forEach((w, i) => checkPrompt(w, `prompts.${kind}[${i}]`, 18));
for (const [date, d] of Object.entries(days)) {
  if (!Array.isArray(d.deep) || d.deep.length !== 5) errors.push(`day ${date}: needs 5 deep prompts`);
  else d.deep.forEach((p, i) => checkPrompt(p.where, `day ${date} prompt ${i + 1}`));
  const tl = d.timeline?.memes || [];
  if (tl.length !== 5 || !tl.every((id) => byId(id))) errors.push(`day ${date}: timeline needs 5 known memes`);
  else if (new Set(tl.map((id) => byId(id).year)).size !== 5) errors.push(`day ${date}: timeline years must all differ`);
}
// The generators must always produce a full puzzle.
for (let i = 0; i < 200; i++) {
  const rng = sandbox.WH.rng(`check-${i}`);
  if (sandbox.WH.memes.genDeep(rng).length !== 5) { errors.push('genDeep produced fewer than 5 prompts'); break; }
  if (sandbox.WH.memes.genTimeline(rng).length !== 5) { errors.push('genTimeline produced fewer than 5 memes'); break; }
}

for (const w of warns) console.log(`WARN  ${w}`);
for (const e of errors) console.log(`ERROR ${e}`);
console.log(`${memes.length} memes, ${Object.values(prompts).flat().length} fallback prompts, ${Object.keys(days).length} curated days: ${errors.length} errors, ${warns.length} warnings`);
if (errors.length) process.exit(1);
if (!process.argv.includes('--check')) {
  writeFileSync(join(root, 'js/data/memes.js'), `// Generated by scripts/build-memes.mjs from content/memes/. Do not edit by hand.
// Row: [id, name, aliases, year, platform, source, star, type, tags, niche, fact]
window.WH_MEMES = ${JSON.stringify(packed)};
window.WH_MEME_PROMPTS = ${JSON.stringify(prompts)};
window.WH_MEME_DAYS = ${JSON.stringify(days)};
`);
  console.log('Wrote js/data/memes.js');
}
