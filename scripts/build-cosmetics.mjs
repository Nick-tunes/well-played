// Copies shared/cosmetics.json (the one source of truth for unlockables, also imported by the
// Worker) into js/data/cosmetics.js for the browser. Run after editing the JSON.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'shared/cosmetics.json'), 'utf8'));
writeFileSync(join(root, 'js/data/cosmetics.js'),
  `// Generated by scripts/build-cosmetics.mjs from shared/cosmetics.json. Do not edit by hand.\nwindow.WH_COSMETICS = ${JSON.stringify(data, null, 2)};\n`);
console.log(`cosmetics: ${data.achievements.length} achievements, ${data.species.length} avatars, ${data.colors.length} colours, ${data.frames.length} frames, ${data.titles.length} titles`);
